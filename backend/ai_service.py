_LOCAL_MODEL = None
_LOCAL_TOKENIZER = None
_LOCAL_MODEL_LOADED = False
_LOCAL_MODEL_LOADING = False


def lora_adapter_available() -> bool:
    """Return True iff a *trained* LoRA adapter directory exists on disk.

    Rejects stubs: the repo ships a 133-byte placeholder at notebooks/lora_model
    that must not be treated as a real trained adapter (which is tens of MB).
    """
    if not os.path.isdir(LORA_ADAPTER_DIR):
        return False
    weights = [f for f in os.listdir(LORA_ADAPTER_DIR)
               if f.endswith((".safetensors", ".bin", ".pt"))]
    if not weights:
        return False
    return any(
        os.path.getsize(os.path.join(LORA_ADAPTER_DIR, f)) >= MIN_REAL_SAFETENSORS_BYTES
        for f in weights
    )


def lazy_load_lora_model() -> bool:
    """Load the LoRA adapter + base model into memory once. Phase 2 only."""
    global _LOCAL_MODEL, _LOCAL_TOKENIZER, _LOCAL_MODEL_LOADED, _LOCAL_MODEL_LOADING

    if _LOCAL_MODEL_LOADED or _LOCAL_MODEL_LOADING:
        return _LOCAL_MODEL_LOADED

    if not USE_LOCAL_LORA:
        logger.info("Local LoRA backend disabled (VIDHANAI_USE_LORA != 1).")
        return False

    if not _lazy_load_transformers():
        logger.warning("transformers/peft not installed; local LoRA backend unavailable.")
        return False

    if not lora_adapter_available():
        logger.warning(
            "No trained LoRA adapter found at %s. Run Phase 2 training first.",
            LORA_ADAPTER_DIR,
        )
        return False

    try:
        _LOCAL_MODEL_LOADING = True
        logger.info("Loading local LoRA adapter from %s ...", LORA_ADAPTER_DIR)

        _LOCAL_TOKENIZER = _AutoTokenizer.from_pretrained(LORA_BASE_MODEL)
        device_map = "auto" if _torch.cuda.is_available() else "cpu"
        base_model = _AutoModelForCausalLM.from_pretrained(
            LORA_BASE_MODEL,
            device_map=device_map,
            torch_dtype=_torch.float16 if _torch.cuda.is_available() else _torch.float32,
            low_cpu_mem_usage=True,
        )
        _LOCAL_MODEL = _PeftModel.from_pretrained(base_model, LORA_ADAPTER_DIR)
        _LOCAL_MODEL_LOADED = True
        logger.info("Local LoRA model loaded successfully on %s.", device_map)
    except Exception as exc:  # pragma: no cover - defensive
        logger.exception("Failed to load local LoRA model: %s", exc)
        _LOCAL_MODEL = None
        _LOCAL_TOKENIZER = None
    finally:
        _LOCAL_MODEL_LOADING = False

    return _LOCAL_MODEL_LOADED


def generate_lora_summary(text: str) -> Optional[str]:
    """Run the locally-loaded QLoRA model on ``text``."""
    if not lazy_load_lora_model() or _LOCAL_MODEL is None or _LOCAL_TOKENIZER is None:
        return None

    try:
        messages = [
            {"role": "system", "content": EXPERT_SYSTEM_PROMPT},
            {"role": "user", "content": f"Simplify this legal text:\n\n{text[:6000]}"},
        ]
        prompt = _LOCAL_TOKENIZER.apply_chat_template(
            messages, tokenize=False, add_generation_prompt=True
        )
        inputs = _LOCAL_TOKENIZER(prompt, return_tensors="pt")
        if _torch.cuda.is_available():
            inputs = {k: v.to("cuda") for k, v in inputs.items()}

        with _torch.no_grad():
            outputs = _LOCAL_MODEL.generate(
                **inputs,
                max_new_tokens=512,
                temperature=0.3,
                top_p=0.9,
                do_sample=True,
                pad_token_id=_LOCAL_TOKENIZER.eos_token_id,
            )

        input_length = inputs["input_ids"].shape[1]
        generated = outputs[0][input_length:]
        return _LOCAL_TOKENIZER.decode(generated, skip_special_tokens=True).strip()
    except Exception as exc:  # pragma: no cover - defensive
        logger.exception("Local LoRA generation failed: %s", exc)
        return None


# ---------------------------------------------------------------------------
# Ollama backend (fine-tuned model, local CPU demo)
# ---------------------------------------------------------------------------

def generate_ollama_summary(text: str) -> Optional[str]:
    """Run the locally-served fine-tuned model through Ollama.

    Talks to Ollama's OpenAI-compatible endpoint (default
    ``http://127.0.0.1:11434/v1``) using the same expert prompt as the Groq and
    LoRA backends, so the model_version stamp tells you honestly which backend
    produced the text. Returns ``None`` on any failure (model not loaded,
    Ollama not running, timeout) so the caller degrades gracefully instead of
    erroring - never fabricates output.
    """
    if not USE_OLLAMA:
        return None
    try:
        import requests as _requests
    except ImportError:  # pragma: no cover - requests is in requirements
        logger.warning("requests not installed; Ollama backend unavailable.")
        return None

    try:
        resp = _requests.post(
            f"{OLLAMA_URL}/chat/completions",
            json={
                "model": OLLAMA_MODEL,
                "messages": [
                    {"role": "system", "content": EXPERT_SYSTEM_PROMPT},
                    {"role": "user", "content": f"Simplify this legal text:\n\n{text[:6000]}"},
                ],
                "temperature": 0.3,
                "top_p": 0.9,
                "max_tokens": OLLAMA_MAX_TOKENS,
            },
            timeout=240,  # CPU 3B can take ~40 s for a full summary; stay generous
        )
        resp.raise_for_status()
        data = resp.json()
        content = (data.get("choices") or [{}])[0].get("message", {}).get("content")
        return (content or "").strip() or None
    except Exception as exc:  # pragma: no cover - network/local server
        logger.warning("Ollama call failed (%s): %s", OLLAMA_URL, exc)
        return None


