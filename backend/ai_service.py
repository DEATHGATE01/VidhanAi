def _split_sentences(text: str) -> list[str]:
    if not text:
        return []
    return [s.strip() for s in re.split(r"(?<=[.!?])\s+", text) if len(s.strip()) > 20]


def _extractive_summary(
    title: str,
    ministry: str,
    status: str,
    introduction_date,
    full_text: str,
    sections: list,
    paragraphs: list,
    date_scraped=None,
) -> str:
    parts = [_format_header(title, ministry, status, introduction_date, date_scraped), ""]

    # Extract TL;DR (3 bullets)
    sentences = _split_sentences(full_text)
    if sentences:
        tldr_bullets = []
        # First sentence = purpose
        tldr_bullets.append(f"• {sentences[0][:200]}")
        # Find penalty/key provision
        for s in sentences[1:6]:
            if any(kw in s.lower() for kw in ['penalty', 'fine', 'imprisonment', 'crore', 'lakh', 'shall', 'must']):
                tldr_bullets.append(f"• {s[:200]}")
                break
        # Last sentence = impact/next step
        if len(sentences) > 2:
            tldr_bullets.append(f"• {sentences[-1][:200]}")

        if len(tldr_bullets) >= 2:
            parts.append("## TL;DR")
            parts.extend(tldr_bullets[:3])
            parts.append("")

    if sentences:
        parts.append("### Overview")
        parts.append(" ".join(sentences[:3]))
    if paragraphs:
        parts.append("\n\n### Key Points")
        for para in paragraphs[:3]:
            if len(para) > 50:
                parts.append(f"- {para}")
    return "\n".join(parts).strip()
