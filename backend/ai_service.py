"""
VidhanAI summarization service.

Phase 1 of the semester plan (reproducibility): this module is intentionally
honest about which model produced each summary. There are three backends:

    1. `groq_expert` (default, production): Groq `groq/compound` (formerly
       `llama-3.3-70b-versatile`, retired) with the domain-specific expert
       prompt. This is what currently serves every user-facing summary.
    2. `local_lora` (Phase 2 only): the QLoRA-fine-tuned Llama-3.2-3B adapter
       at ``notebooks/lora_model``. Opt-in via the ``VIDHANAI_USE_LORA=1`` env
       var so we never silently fall back from a real adapter run to Groq.
    3. `extractive` (last-resort fallback): rule-based extraction from the
       bill text when neither model is available. Only used when both LLM
       backends fail or no full text is present.

Every summary records ``model_version`` so we can audit which backend produced
it and ``guardrail_applied`` so reviewers can confirm disclaimer enforcement.
"""
from __future__ import annotations

import logging
import os
import re
from datetime import datetime
from typing import Optional

logger = logging.getLogger(__name__)

