def semantic_search(query: str, n_results: int = 5) -> list[dict]:
    """Query the ChromaDB ``legal_bills`` collection."""
    if not CHROMADB_AVAILABLE:
        logger.warning("chromadb not installed; semantic search disabled.")
        return []

    project_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    db_path = os.path.join(project_root, "instance", "chroma_db")
    if not os.path.isdir(db_path):
        logger.info("ChromaDB not found at %s; skipping semantic search.", db_path)
        return []

    try:
        client = chromadb.PersistentClient(path=db_path)
        ef = embedding_functions.SentenceTransformerEmbeddingFunction(
            model_name="all-MiniLM-L6-v2"
        )
        collection = client.get_collection(name="legal_bills", embedding_function=ef)
        results = collection.query(query_texts=[query], n_results=n_results)
        if not results or not results.get("documents"):
            return []
        documents = results["documents"][0]
        metadatas = (results.get("metadatas") or [[]])[0]
        distances = (results.get("distances") or [[]])[0] if results.get("distances") else []
        return [
            {
                "text": documents[i],
                "metadata": metadatas[i] if i < len(metadatas) else {},
                "distance": distances[i] if i < len(distances) else None,
            }
            for i in range(len(documents))
        ]
    except Exception as exc:  # pragma: no cover
        logger.exception("Semantic search failed: %s", exc)
        return []


