# Only imported when USE_LOCAL_LORA=1 and model is actually needed
TRANSFORMERS_AVAILABLE = None
_torch = None
_AutoModelForCausalLM = None
_AutoTokenizer = None
_PeftModel = None

def _lazy_load_transformers():
    """Lazy-load transformers, torch, and peft only when needed."""
    global TRANSFORMERS_AVAILABLE, _torch, _AutoModelForCausalLM, _AutoTokenizer, _PeftModel
    if TRANSFORMERS_AVAILABLE is not None:
        return TRANSFORMERS_AVAILABLE
    try:
        import torch
        from transformers import AutoModelForCausalLM, AutoTokenizer
        from peft import PeftModel
        _torch = torch
        _AutoModelForCausalLM = AutoModelForCausalLM
        _AutoTokenizer = AutoTokenizer
        _PeftModel = PeftModel
        TRANSFORMERS_AVAILABLE = True
    except ImportError:
        TRANSFORMERS_AVAILABLE = False
    return TRANSFORMERS_AVAILABLE


