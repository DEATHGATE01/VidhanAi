_NON_LEGAL_KEYWORDS = (
    "write a story",
    "joke",
    "recipe",
    "poem",
    "how to make a bomb",
    "ignore previous",
    "write code",
    "pretend you are",
)


def check_input_guardrails(query: str) -> tuple[bool, str]:
    """Reject obvious non-legal queries before they reach the model."""
    if not query:
        return True, ""
    lowered = query.lower()
    for kw in _NON_LEGAL_KEYWORDS:
        if kw in lowered:
            return False, (
                "Query rejected: this query appears to be outside the scope of "
                "Indian legislation. Please ask a question related to bills, acts, "
                "or parliamentary proceedings."
            )
    return True, ""


def append_legal_disclaimer(summary: str) -> str:
    """Output guardrail: append the standard legal disclaimer."""
    return summary + LEGAL_DISCLAIMER


