def _format_header(title: str, ministry: str, status: str, introduction_date, date_scraped=None) -> str:
    parts = [f"## {title}", ""]
    if ministry:
        parts.append(f"**Ministry:** {ministry}  ")
    if status:
        parts.append(f"**Status:** {status}  ")
    # Use introduction_date if available, otherwise fall back to date_scraped
    display_date = introduction_date or date_scraped
    if display_date:
        try:
            dt = datetime.fromisoformat(str(display_date).replace("Z", "+00:00"))
            parts.append(f"**Introduced:** {dt.strftime('%B %d, %Y')}  ")
        except Exception:
            pass
    return "\n".join(parts)


def generate_bill_summary(bill_data: dict, content_data: dict) -> dict:
    """Produce a structured summary for one bill.

    Returns a dict with keys: ``summary``, ``summary_type``, ``model_version``,
    ``guardrail_applied``, ``sentiment_score``, ``generated_at``, ``word_count``,
    ``confidence``.
    """
    title = bill_data.get("title", "Untitled Bill")
    ministry = (bill_data.get("ministry") or "").strip()
    status = (bill_data.get("status") or "").strip()
    introduction_date = bill_data.get("introduction_date")
    date_scraped = bill_data.get("date_scraped")

    full_text = (content_data or {}).get("full_text") or ""
    sections = (content_data or {}).get("sections") or []
    paragraphs = (content_data or {}).get("paragraphs") or []

    summary_text = ""
    summary_type = "extractive"
    model_version = "rule_based_extractive_v1"
    confidence = 0.5

    if full_text:
        # Try the configured backends in priority order: locally fine-tuned
        # model (Ollama) → local LoRA → Groq. Enabling the Ollama backend makes
        # the fine-tuned model the generative engine for the running app; when
        # it is unset (cloud deploys) behavior is unchanged and Groq serves.
        backend_chain = []
        if USE_OLLAMA:
            backend_chain.append(("ollama", generate_ollama_summary))
        if USE_LOCAL_LORA:
            backend_chain.append(("local_lora", generate_lora_summary))
        backend_chain.append(("groq_expert", generate_groq_summary))

        for backend_name, backend_fn in backend_chain:
            result = backend_fn(full_text)
            if result:
                header = _format_header(title, ministry, status, introduction_date, date_scraped)
                summary_text = f"{header}\n\n### AI Generative Summary\n{result}"
                summary_type = "generative"
                if backend_name == "ollama":
                    model_version = f"local_ollama_{OLLAMA_MODEL}"
                    confidence = 0.9
                elif backend_name == "local_lora":
                    model_version = f"local_lora_{LORA_BASE_MODEL.split('/')[-1]}"
                    confidence = 0.92
                elif backend_name == "groq_expert":
                    model_version = f"groq_{GROQ_MODEL_NAME}"
                    confidence = 0.88
                break

    # The generative model output already leads with a '## TL;DR' section (see
    # EXPERT_SYSTEM_PROMPT) and contains the full body, so no separate TL;DR
    # extraction/reassembly happens here — earlier code that re-sliced from
    # '## TL;DR' to the next '###' marker swallowed the WHOLE document (models
    # use '##' section headings, so no terminator matched) and then re-appended
    # it, producing a duplicated, confusing summary.

    if not summary_text:
        # Last-resort: rule-based extractive summary.
        summary_text = _extractive_summary(
            title, ministry, status, introduction_date,
            full_text, sections, paragraphs, date_scraped,
        )
        summary_type = "extractive"
        model_version = "rule_based_extractive_v1"
        confidence = 0.6

    summary_with_disclaimer = append_legal_disclaimer(summary_text)
    sentiment_score = analyze_sentiment(full_text)

    return {
        "summary": summary_with_disclaimer,
        "summary_type": summary_type,
        "model_version": model_version,
        "guardrail_applied": True,
        "sentiment_score": sentiment_score,
        "generated_at": datetime.utcnow().isoformat(),
        "word_count": len(summary_with_disclaimer.split()),
        "confidence": confidence,
    }


def generate_quick_summary(bill_data: dict) -> dict:
    """One-line summary used when full text isn't available."""
    title = bill_data.get("title", "Bill")
    ministry = bill_data.get("ministry", "")
    status = bill_data.get("status", "")
    introduction_date = bill_data.get("introduction_date")
    date_scraped = bill_data.get("date_scraped")
    header = _format_header(title, ministry, status, introduction_date, date_scraped)
    sentence = f"This bill titled '{title}'"
    if ministry:
        sentence += f" from the {ministry}"
    if status:
        sentence += f" is currently {status.lower()}"
    else:
        sentence += " is under consideration"
    sentence += ". Detailed provisions and objectives are being analyzed."
    return {
        "summary": append_legal_disclaimer(f"{header}\n\n{sentence}"),
        "summary_type": "quick",
        "model_version": "rule_based_quick_v1",
        "guardrail_applied": True,
        "generated_at": datetime.utcnow().isoformat(),
        "word_count": len(sentence.split()),
        "confidence": 0.5,
    }


def generate_change_narrative(diff: dict) -> dict:
    """Turn a structural diff dict into a human-readable narrative.

    Uses the LLM Service (LoRA + Groq fallback). The diff itself is
    already structured; the LLM only narrates the change list.

    Returns the same dict shape as generate_bill_summary so callers can
    stamp model_version / guardrail_applied uniformly.
    """
    diff_summary = diff.get("diff_summary_text") or ""
    if not diff_summary:
        from services.amendment_service import diff_summary_text
        diff_summary = diff_summary_text(diff)

    # Build a compact prompt with the structural facts the LLM must narrate.
    facts_added = diff.get("facts_added", [])[:10]
    facts_removed = diff.get("facts_removed", [])[:10]
    sections_modified = diff.get("modified_sections", [])[:3]
    sections_added = diff.get("added_sections", [])[:3]
    sections_removed = diff.get("removed_sections", [])[:3]
    stats = diff.get("stats", {})

    # Build explicit, unambiguous facts for the LLM
    added_titles = [s['title'] for s in sections_added]
    removed_titles = [s['title'] for s in sections_removed]
    modified_titles = [s['title'] for s in sections_modified]

    user_payload = (
        f"v1: {diff.get('title_v1','')}\n"
        f"v2: {diff.get('title_v2','')}\n\n"
        f"STRUCTURAL DIFF STATS (MUST BE ACCURATE IN NARRATIVE):\n"
        f"  v1 had {stats.get('v1_sections',0)} section(s); v2 has {stats.get('v2_sections',0)} section(s)\n"
        f"  Sections ADDED in v2 (not in v1): {stats.get('added',0)} — {added_titles if added_titles else 'none'}\n"
        f"  Sections REMOVED in v2 (were in v1): {stats.get('removed',0)} — {removed_titles if removed_titles else 'none'}\n"
        f"  Sections MODIFIED (same title, different content): {stats.get('modified',0)} — {modified_titles if modified_titles else 'none'}\n\n"
        f"FACT CHANGES (penalties, dates, amounts):\n"
        f"  NEW facts in v2 (not in v1): {facts_added if facts_added else 'none'}\n"
        f"  OLD facts REMOVED from v1 (not in v2): {facts_removed if facts_removed else 'none'}\n\n"
        "INSTRUCTIONS:\n"
        "Write a 3-5 sentence plain-English narrative of what changed between v1 and v2.\n"
        "MUST accurately reflect the stats above — do NOT contradict the numbers above.\n"
        "Focus on concrete facts (penalties, dates, jurisdictions) and sections added/removed/modified.\n"
        "Do NOT say 'added X sections' if stats show different numbers.\n"
        "Do NOT include meta-commentary about your approach."
    )

    narrative = ""
    model_version = "rule_based_diff_narrative_v1"
    confidence = 0.55
    if USE_OLLAMA:
        ollama_out = generate_ollama_summary(user_payload)
        if ollama_out:
            narrative = ollama_out
            model_version = f"local_ollama_{OLLAMA_MODEL}"
            confidence = 0.9
    if not narrative and USE_LOCAL_LORA:
        lora_out = generate_lora_summary(user_payload)
        if lora_out:
            narrative = lora_out
            model_version = f"local_lora_{LORA_BASE_MODEL.split('/')[-1]}"
            confidence = 0.9
    if not narrative:
        groq_out = generate_groq_summary(user_payload)
        if groq_out:
            narrative = groq_out
            model_version = f"groq_{GROQ_MODEL_NAME}"
            confidence = 0.85

    if not narrative:
        # Honest rule-based fallback: list the facts verbatim.
        lines = [
            f"Changes between {diff.get('title_v1','v1')} and {diff.get('title_v2','v2')}:",
            diff_summary,
        ]
        narrative = "\n\n".join(lines)

    return {
        "narrative": append_legal_disclaimer(narrative),
        "model_version": model_version,
        "guardrail_applied": True,
        "confidence": confidence,
        "diff_summary_text": diff_summary,
        "facts_added": facts_added,
        "facts_removed": facts_removed,
    }


